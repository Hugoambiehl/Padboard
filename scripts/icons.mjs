#!/usr/bin/env node
// Generates every app icon from the single source assets/icon/padboard.svg:
//
//   node scripts/icons.mjs
//
// - desktop (apps/desktop/src-tauri/icons): PNGs for the Linux package and
//   the window, a multi-size Windows .ico, the tray icon;
// - frontend favicon (apps/desktop/public/favicon.svg);
// - tablet: adaptive icon (violet background, the tiles as a vector
//   foreground inside the safe zone) and its monochrome layer (Android 13+
//   themed icons), as vector drawables.
//
// At 32 px and below the "pressed" halo is under a pixel wide and only
// blurs the tile: those sizes use the source without it (SMALL_MAX).
// PNGs are rendered by `tauri icon` (resvg), from apps/desktop's npm deps.
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const desktop = join(root, "apps/desktop");
const icons = join(desktop, "src-tauri/icons");
const res = join(root, "apps/android/app/src/main/res");

/** Largest size drawn without the halo. */
const SMALL_MAX = 32;
const DESKTOP_PNGS = { "32x32.png": 32, "128x128.png": 128, "128x128@2x.png": 256, "icon.png": 512 };
const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];
/** Tray: 32 px for 100 % scaling, 64 px for HiDPI. */
const TRAY_PNGS = { "tray.png": 32, "tray@2x.png": 64 };

const GENERATED = "Generated by scripts/icons.mjs from assets/icon/padboard.svg: do not edit.";

// ─── Source ─────────────────────────────────────────────────────────────
const source = readFileSync(join(root, "assets/icon/padboard.svg"), "utf8");
const rectTags = source.match(/<rect\b[^>]*\/>/gs) ?? [];
const rects = rectTags.map((tag) => {
  const attrs = Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
  return { tag, attrs };
});
const isHalo = (r) => r.attrs.fill === "none" && r.attrs.stroke;
if (rects.length < 2 || rects.filter(isHalo).length !== 1) {
  throw new Error("assets/icon/padboard.svg: expected a background rect, tiles and one stroked halo");
}
const small = source.replace(rects.find(isHalo).tag, "").replace(/\n\s*\n/g, "\n");

// ─── PNG rendering ──────────────────────────────────────────────────────
const work = mkdtempSync(join(tmpdir(), "padboard-icons-"));
function render(svg, sizes) {
  const input = join(work, `src-${sizes.join("-")}.svg`);
  const out = join(work, `out-${sizes.join("-")}`);
  writeFileSync(input, svg);
  execFileSync("npx", ["tauri", "icon", input, "-o", out, "-p", sizes.join(",")], {
    cwd: desktop,
    stdio: "ignore",
  });
  return Object.fromEntries(sizes.map((s) => [s, readFileSync(join(out, `${s}x${s}.png`))]));
}
const allSizes = [
  ...new Set([...Object.values(DESKTOP_PNGS), ...ICO_SIZES, ...Object.values(TRAY_PNGS)]),
];
const png = {
  ...render(source, allSizes.filter((s) => s > SMALL_MAX)),
  ...render(small, allSizes.filter((s) => s <= SMALL_MAX)),
};

// ─── Desktop ────────────────────────────────────────────────────────────
// Only what Padboard uses (Windows, Linux): the default macOS / Store files go.
for (const f of readdirSync(icons)) rmSync(join(icons, f));
for (const [name, size] of Object.entries({ ...DESKTOP_PNGS, ...TRAY_PNGS })) {
  writeFileSync(join(icons, name), png[size]);
}
writeFileSync(join(icons, "icon.ico"), ico(ICO_SIZES.map((s) => [s, png[s]])));

/** A Windows icon holding PNG images (supported since Windows Vista). */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2); // icon
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(([size, data], i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e); // 0 = 256
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4); // planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map(([, data]) => data)]);
}

// Favicon: drawn small in a tab, so without the halo.
mkdirSync(join(desktop, "public"), { recursive: true });
writeFileSync(join(desktop, "public/favicon.svg"), small.trim() + "\n");

// ─── Android ────────────────────────────────────────────────────────────
// Adaptive icon: 108 dp canvas, the launcher shows the central 72 dp (the
// source's 256 units), the safe zone is a 66 dp circle.
const SCALE = 72 / 256;
const OFFSET = (108 - 256 * SCALE) / 2;

/** Path data of a rounded rectangle. */
function roundedRect({ x, y, width, height, rx }) {
  const [X, Y, W, H, R] = [x, y, width, height, rx ?? 0].map(Number);
  return (
    `M${X + R},${Y} h${W - 2 * R} a${R},${R} 0 0 1 ${R},${R} v${H - 2 * R} ` +
    `a${R},${R} 0 0 1 -${R},${R} h-${W - 2 * R} a${R},${R} 0 0 1 -${R},-${R} ` +
    `v-${H - 2 * R} a${R},${R} 0 0 1 ${R},-${R} z`
  );
}

/** The tiles (every rect but the background) as vector drawable paths. */
function foreground(monochrome) {
  return rects
    .slice(1)
    .map(({ attrs }) => {
      const d = roundedRect(attrs);
      const color = (c) => (monochrome ? "#FFFFFF" : c);
      if (isHalo({ attrs })) {
        return (
          `        <path android:pathData="${d}" android:strokeColor="${color(attrs.stroke)}"\n` +
          `            android:strokeWidth="${attrs["stroke-width"]}" android:strokeAlpha="${attrs.opacity ?? 1}" />`
        );
      }
      return `        <path android:pathData="${d}" android:fillColor="${color(attrs.fill)}" />`;
    })
    .join("\n");
}

function vector(monochrome) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:scaleX="${SCALE}" android:scaleY="${SCALE}"
        android:translateX="${OFFSET}" android:translateY="${OFFSET}">
${foreground(monochrome)}
    </group>
</vector>
`;
}

writeFileSync(join(res, "drawable/ic_launcher_foreground.xml"), vector(false));
writeFileSync(join(res, "drawable/ic_launcher_monochrome.xml"), vector(true));
writeFileSync(
  join(res, "drawable/ic_launcher_background.xml"),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="${rects[0].attrs.fill}" />
</shape>
`,
);
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
writeFileSync(join(res, "mipmap-anydpi/ic_launcher.xml"), adaptive);
writeFileSync(join(res, "mipmap-anydpi/ic_launcher_round.xml"), adaptive);
// minSdk 26: every launcher uses the adaptive icon, the template's bitmaps go.
for (const dir of readdirSync(res).filter((d) => /^mipmap-.*dpi$/.test(d) && d !== "mipmap-anydpi")) {
  rmSync(join(res, dir), { recursive: true });
}

rmSync(work, { recursive: true });
console.log("icons generated");
