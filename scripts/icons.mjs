#!/usr/bin/env node
// Generates every app icon from the single source assets/icon/padboard.svg:
//
//   node scripts/icons.mjs
//
// - desktop (apps/desktop/src-tauri/icons): PNGs for the Linux package and
//   the window, a multi-size Windows .ico, the tray icon;
// - frontend favicon (apps/desktop/public/favicon.svg);
// - tablet: adaptive icon (violet background, the tiles as a vector
//   foreground inside the safe zone) and its monochrome layer (Android 13+
//   themed icons), as vector drawables (Android 8+, mipmap-anydpi-v26);
//   PNG launcher icons for Android 7.x, square and round (mipmap-*dpi);
//   and the whole icon as a drawable for the app's own header badge
//   (ic_padboard.xml);
// - store listing icon (fastlane/metadata/android/<locale>/images/icon.png);
// - Windows installer (NSIS) images, 24-bit BMPs at the sizes NSIS asks
//   for: the header (150×57, also the uninstaller's) and the sidebar of
//   the welcome and finish pages (164×314).
//
// At 32 px and below the "pressed" halo is under a pixel wide and only
// blurs the tile: those sizes use the source without it (SMALL_MAX).
// PNGs are rendered by `tauri icon` (resvg), from apps/desktop's npm deps.
import { execFileSync } from "node:child_process";
import { inflateSync } from "node:zlib";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const desktop = join(root, "apps/desktop");
const icons = join(desktop, "src-tauri/icons");
const res = join(root, "apps/android/app/src/main/res");

/** Largest size drawn without the halo. */
const SMALL_MAX = 32;
const DESKTOP_PNGS = { "32x32.png": 32, "128x128.png": 128, "128x128@2x.png": 256, "icon.png": 512 };
const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];
/** Tray: 32 px for 100 % scaling, 64 px for HiDPI. */
const TRAY_PNGS = { "tray.png": 32, "tray@2x.png": 64 };
/** Store listing icons (512 px), one per fastlane metadata locale. */
const FASTLANE_LOCALES = ["en-US", "fr-FR"];

const GENERATED = "Generated by scripts/icons.mjs from assets/icon/padboard.svg: do not edit.";

// ─── Source ─────────────────────────────────────────────────────────────
const source = readFileSync(join(root, "assets/icon/padboard.svg"), "utf8");
const rectTags = source.match(/<rect\b[^>]*\/>/gs) ?? [];
const rects = rectTags.map((tag) => {
  const attrs = Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
  return { tag, attrs };
});
const isHalo = (r) => r.attrs.fill === "none" && r.attrs.stroke;
if (rects.length < 2 || rects.filter(isHalo).length !== 1) {
  throw new Error("assets/icon/padboard.svg: expected a background rect, tiles and one stroked halo");
}
const small = source.replace(rects.find(isHalo).tag, "").replace(/\n\s*\n/g, "\n");

// ─── PNG rendering ──────────────────────────────────────────────────────
const work = mkdtempSync(join(tmpdir(), "padboard-icons-"));
function render(svg, sizes, name = "") {
  const input = join(work, `src${name}-${sizes.join("-")}.svg`);
  const out = join(work, `out${name}-${sizes.join("-")}`);
  writeFileSync(input, svg);
  execFileSync("npx", ["tauri", "icon", input, "-o", out, "-p", sizes.join(",")], {
    cwd: desktop,
    stdio: "ignore",
  });
  return Object.fromEntries(sizes.map((s) => [s, readFileSync(join(out, `${s}x${s}.png`))]));
}
const allSizes = [
  ...new Set([...Object.values(DESKTOP_PNGS), ...ICO_SIZES, ...Object.values(TRAY_PNGS)]),
];
const png = {
  ...render(source, allSizes.filter((s) => s > SMALL_MAX)),
  ...render(small, allSizes.filter((s) => s <= SMALL_MAX)),
};

// ─── Desktop ────────────────────────────────────────────────────────────
// Only what Padboard uses (Windows, Linux): the default macOS / Store files go.
for (const f of readdirSync(icons)) rmSync(join(icons, f));
for (const [name, size] of Object.entries({ ...DESKTOP_PNGS, ...TRAY_PNGS })) {
  writeFileSync(join(icons, name), png[size]);
}
writeFileSync(join(icons, "icon.ico"), ico(ICO_SIZES.map((s) => [s, png[s]])));

// ─── Store listings (fastlane metadata, read by F-Droid / IzzyOnDroid) ──
for (const locale of FASTLANE_LOCALES) {
  const dir = join(root, "fastlane/metadata/android", locale, "images");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "icon.png"), png[512]);
}

/** A Windows icon holding PNG images (supported since Windows Vista). */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2); // icon
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(([size, data], i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e); // 0 = 256
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4); // planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map(([, data]) => data)]);
}

// ─── Windows installer (NSIS) ───────────────────────────────────────────
// `tauri icon` renders squares: each image is drawn in the corner of a
// square canvas, then cropped. Dark background, the icon, and a grid of
// tiles in the category colours (the tablet's grid).
const inner = source.replace(/^[\s\S]*?<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const BACKGROUND = "#0E0F12";
const CATEGORIES = ["#8B7CFF", "#5AA9FF", "#3DD6B5", "#FF9F5A", "#FF6FAE", "#FF5C5C", "#A3ABBD"];

/** The icon at (x, y), `size` wide. */
const icon = (x, y, size) =>
  `<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="0 0 256 256">${inner}</svg>`;

/** A tile: the category colour at 16 % behind a small square of it. */
function tile(x, y, size, color) {
  const dot = size * 0.36;
  const o = (size - dot) / 2;
  return (
    `<rect x="${x}" y="${y}" width="${size}" height="${size}" rx="${size * 0.28}" fill="${color}" fill-opacity="0.16"/>` +
    `<rect x="${x + o}" y="${y + o}" width="${dot}" height="${dot}" rx="${dot * 0.3}" fill="${color}"/>`
  );
}

/** `width`×`height` image drawn by `body`, as a BMP. */
function installerImage(width, height, body) {
  const side = Math.max(width, height);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${side} ${side}">` +
    `<rect width="${width}" height="${height}" fill="${BACKGROUND}"/>${body}</svg>`;
  const { pixels, width: w } = decodePng(render(svg, [side])[side]);
  return bmp(width, height, (x, y) => pixels.subarray((y * w + x) * 4, (y * w + x) * 4 + 3));
}

const sidebarTiles = [];
for (let row = 0; row < 3; row++) {
  for (let col = 0; col < 3; col++) {
    const i = row * 3 + col;
    sidebarTiles.push(tile(18 + col * 46, 176 + row * 46, 36, CATEGORIES[i % CATEGORIES.length]));
  }
}
writeFileSync(
  join(icons, "nsis-sidebar.bmp"),
  installerImage(164, 314, icon(34, 44, 96) + sidebarTiles.join("")),
);
writeFileSync(
  join(icons, "nsis-header.bmp"),
  installerImage(
    150,
    57,
    icon(8, 8, 41) + [1, 2, 3].map((c, i) => tile(62 + i * 28, 17, 23, CATEGORIES[c])).join(""),
  ),
);

/** RGBA pixels of a PNG as `tauri icon` writes it (8-bit RGBA, not interlaced). */
function decodePng(data) {
  let pos = 8;
  let width = 0;
  let height = 0;
  const idat = [];
  while (pos < data.length) {
    const length = data.readUInt32BE(pos);
    const type = data.toString("latin1", pos + 4, pos + 8);
    const chunk = data.subarray(pos + 8, pos + 8 + length);
    if (type === "IHDR") {
      width = chunk.readUInt32BE(0);
      height = chunk.readUInt32BE(4);
      if (chunk[8] !== 8 || chunk[9] !== 6 || chunk[12] !== 0) {
        throw new Error("expected an 8-bit RGBA, non-interlaced PNG");
      }
    } else if (type === "IDAT") idat.push(chunk);
    pos += 12 + length;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * 4;
  const pixels = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    for (let i = 0; i < stride; i++) {
      const value = raw[y * (stride + 1) + 1 + i];
      const a = i >= 4 ? pixels[y * stride + i - 4] : 0;
      const b = y > 0 ? pixels[(y - 1) * stride + i] : 0;
      const c = i >= 4 && y > 0 ? pixels[(y - 1) * stride + i - 4] : 0;
      let predicted = 0;
      if (filter === 1) predicted = a;
      else if (filter === 2) predicted = b;
      else if (filter === 3) predicted = (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a);
        const pb = Math.abs(p - b);
        const pc = Math.abs(p - c);
        predicted = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      pixels[y * stride + i] = (value + predicted) & 0xff;
    }
  }
  return { pixels, width };
}

/** A 24-bit BMP (bottom-up rows, padded to 4 bytes); `rgb(x, y)` gives each pixel. */
function bmp(width, height, rgb) {
  const row = Math.ceil((width * 3) / 4) * 4;
  const out = Buffer.alloc(54 + row * height);
  out.write("BM", 0, "latin1");
  out.writeUInt32LE(out.length, 2);
  out.writeUInt32LE(54, 10);
  out.writeUInt32LE(40, 14);
  out.writeInt32LE(width, 18);
  out.writeInt32LE(height, 22);
  out.writeUInt16LE(1, 26);
  out.writeUInt16LE(24, 28);
  out.writeUInt32LE(row * height, 34);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const [r, g, b] = rgb(x, y);
      const at = 54 + (height - 1 - y) * row + x * 3;
      out[at] = b;
      out[at + 1] = g;
      out[at + 2] = r;
    }
  }
  return out;
}

// Favicon: drawn small in a tab, so without the halo.
mkdirSync(join(desktop, "public"), { recursive: true });
writeFileSync(join(desktop, "public/favicon.svg"), small.trim() + "\n");

// ─── Android ────────────────────────────────────────────────────────────
// Adaptive icon: 108 dp canvas, the launcher shows the central 72 dp (the
// source's 256 units), the safe zone is a 66 dp circle.
const SCALE = 72 / 256;
const OFFSET = (108 - 256 * SCALE) / 2;

/** Path data of a rounded rectangle. */
function roundedRect({ x, y, width, height, rx }) {
  const [X, Y, W, H, R] = [x, y, width, height, rx ?? 0].map(Number);
  return (
    `M${X + R},${Y} h${W - 2 * R} a${R},${R} 0 0 1 ${R},${R} v${H - 2 * R} ` +
    `a${R},${R} 0 0 1 -${R},${R} h-${W - 2 * R} a${R},${R} 0 0 1 -${R},-${R} ` +
    `v-${H - 2 * R} a${R},${R} 0 0 1 ${R},-${R} z`
  );
}

/** The tiles (every rect but the background) as vector drawable paths. */
function foreground(monochrome) {
  return rects
    .slice(1)
    .map(({ attrs }) => {
      const d = roundedRect(attrs);
      const color = (c) => (monochrome ? "#FFFFFF" : c);
      if (isHalo({ attrs })) {
        return (
          `        <path android:pathData="${d}" android:strokeColor="${color(attrs.stroke)}"\n` +
          `            android:strokeWidth="${attrs["stroke-width"]}" android:strokeAlpha="${attrs.opacity ?? 1}" />`
        );
      }
      return `        <path android:pathData="${d}" android:fillColor="${color(attrs.fill)}" />`;
    })
    .join("\n");
}

function vector(monochrome) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:scaleX="${SCALE}" android:scaleY="${SCALE}"
        android:translateX="${OFFSET}" android:translateY="${OFFSET}">
${foreground(monochrome)}
    </group>
</vector>
`;
}

writeFileSync(join(res, "drawable/ic_launcher_foreground.xml"), vector(false));
writeFileSync(join(res, "drawable/ic_launcher_monochrome.xml"), vector(true));
writeFileSync(
  join(res, "drawable/ic_launcher_background.xml"),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="${rects[0].attrs.fill}" />
</shape>
`,
);
// The whole icon (background included), drawn in the app's headers (34 and
// 52 dp: always above SMALL_MAX on the tablet, so with the halo).
const [bg] = rects;
writeFileSync(
  join(res, "drawable/ic_padboard.xml"),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${bg.attrs.width}dp"
    android:height="${bg.attrs.height}dp"
    android:viewportWidth="${bg.attrs.width}"
    android:viewportHeight="${bg.attrs.height}">
        <path android:pathData="${roundedRect(bg.attrs)}" android:fillColor="${bg.attrs.fill}" />
${foreground(false)}
</vector>
`,
);

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
// Android 8+ (adaptive icons need API 26); Android 7.x takes the PNGs below.
rmSync(join(res, "mipmap-anydpi"), { recursive: true, force: true });
mkdirSync(join(res, "mipmap-anydpi-v26"), { recursive: true });
writeFileSync(join(res, "mipmap-anydpi-v26/ic_launcher.xml"), adaptive);
writeFileSync(join(res, "mipmap-anydpi-v26/ic_launcher_round.xml"), adaptive);

// Android 7.x (minSdk 24): bitmap launcher icons, 48 dp at each density.
// The round one (roundIcon, Android 7.1 launchers) has a circular background:
// the tiles stay inside it (farthest corner 110 units from the centre, radius 128).
const LEGACY = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
const round = source.replace(rects[0].tag, rects[0].tag.replace(/rx="[^"]*"/, `rx="${Number(bg.attrs.width) / 2}"`));
if (round === source) throw new Error("assets/icon/padboard.svg: could not make the round icon");
const legacySizes = [...new Set(Object.values(LEGACY))];
const squarePng = render(source, legacySizes, "-square");
const roundPng = render(round, legacySizes, "-round");
for (const [density, size] of Object.entries(LEGACY)) {
  const dir = join(res, `mipmap-${density}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "ic_launcher.png"), squarePng[size]);
  writeFileSync(join(dir, "ic_launcher_round.png"), roundPng[size]);
}

rmSync(work, { recursive: true });
console.log("icons generated");
