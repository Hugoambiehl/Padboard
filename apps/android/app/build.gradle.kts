// Release signing key: a properties file outside the repo (storeFile, keyAlias,
// storePassword), named by the `padboard.signing` Gradle property (in
// ~/.gradle/gradle.properties) or PADBOARD_SIGNING. Without it, release APKs
// are unsigned. See docs/release-signing.md.
val releaseSigning: Properties? =
    (providers.gradleProperty("padboard.signing").orNull ?: System.getenv("PADBOARD_SIGNING"))
        ?.let(::file)
        ?.takeIf { it.isFile }
        ?.let { f -> Properties().apply { f.inputStream().use(::load) } }

android {
    namespace = "io.github.hugoambiehl.padboard"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "io.github.hugoambiehl.padboard"
        minSdk = 26
        targetSdk = 37
        versionCode = 10099
        versionName = "0.1.0"
        // Tests of updates only (docs/development.md): another version for
        // a test APK, e.g. -Ppadboard.testVersionCode=20002
        // -Ppadboard.testVersionName=0.2.0-rc.2. Never used for a release.
        providers.gradleProperty("padboard.testVersionCode").orNull?.let { versionCode = it.toInt() }
        providers.gradleProperty("padboard.testVersionName").orNull?.let { versionName = it }

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (releaseSigning != null) {
            create("release") {
                storeFile = file(releaseSigning.getProperty("storeFile"))
                storePassword = releaseSigning.getProperty("storePassword")
                keyAlias = releaseSigning.getProperty("keyAlias")
                keyPassword = releaseSigning.getProperty("keyPassword") ?: storePassword
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            optimization {
                enable = true
                packageScope = setOf("androidx.**", "kotlin.**", "kotlinx.**")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
    dependenciesInfo {
        // No dependency metadata blob (encrypted for Google Play) in the
        // signing block: IzzyOnDroid and F-Droid flag it.
        includeInApk = false
        includeInBundle = false
    }
    testOptions {
        unitTests.all {
            // Protocol fixtures shared with the Rust tests (cross-language contract).
            it.systemProperty(
                "padboard.fixtures",
                rootProject.file("../../crates/protocol/fixtures").absolutePath
            )
        }
    }
}

